
import json
from datetime import datetime, timezone
from pathlib import Path

from src.correlator import correlate_incident


PROJECT_ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = PROJECT_ROOT / "outputs"


def ensure_output_directory():
    """Create the output folder if it does not already exist."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def build_report(evidence, incidents):
    """Build a report containing scope, findings and limitations."""
    total_events = sum(len(events) for events in evidence.values())

    return {
        "report_title": "SOC Detective - Correlated Incident Finding Report",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "case_id": "CASE-DAY4-001",
        "environment": "Synthetic training environment",
        "total_events_reviewed": total_events,
        "event_counts": {
            source: len(events)
            for source, events in evidence.items()
        },
        "incident_count": len(incidents),
        "incidents": incidents,
        "analyst_conclusion": (
            "The synthetic evidence contains a suspicious authentication "
            "sequence with related endpoint and network activity. Further "
            "validation is required before declaring a confirmed compromise."
        ),
        "limitations": [
            "All records are fictional and intended for training.",
            "Correlation by host and time does not prove causation.",
            "The authentication and network source IP addresses differ.",
            "The rules are illustrative and are not production-tuned.",
            "No live SIEM or endpoint collection system was queried."
        ],
        "recommended_next_steps": [
            "Validate the account owner and whether the activity was expected.",
            "Review original Windows and endpoint event records.",
            "Verify network connections using trusted sensor data.",
            "Check relevant account privileges and recent account changes.",
            "Escalate according to the organisation's incident response process."
        ]
    }


def save_json_report(report):
    """Write the complete findings as JSON."""
    path = OUTPUT_DIR / "incident_report.json"

    with path.open("w", encoding="utf-8") as file:
        json.dump(report, file, indent=2)

    return path


def save_markdown_report(report):
    """Write a readable incident report in Markdown."""
    path = OUTPUT_DIR / "incident_report.md"

    lines = [
        f"# {report['report_title']}",
        "",
        f"**Case ID:** {report['case_id']}",
        f"**Generated (UTC):** {report['generated_at_utc']}",
        f"**Environment:** {report['environment']}",
        "",
        "## Executive Summary",
        "",
        report["analyst_conclusion"],
        "",
        "## Evidence Reviewed",
        "",
        f"- Total events: {report['total_events_reviewed']}",
        f"- Correlated incidents: {report['incident_count']}",
        ""
    ]

    for source, count in report["event_counts"].items():
        lines.append(f"- {source.title()}: {count} events")

    lines.extend(["", "## Incident Findings", ""])

    if not report["incidents"]:
        lines.append("No incidents were generated by the current rules.")
    else:
        for incident in report["incidents"]:
            lines.extend([
                f"### {incident['incident_id']}: {incident['title']}",
                "",
                f"- **Account:** {incident['account']}",
                f"- **Host:** {incident['host']}",
                f"- **Authentication source:** {incident['source_ip']}",
                f"- **Successful logon:** {incident['successful_logon']}",
                f"- **Related process records:** "
                f"{incident['related_process_count']}",
                f"- **Related network records:** "
                f"{incident['related_network_count']}",
                "",
                "**Evidence timeline:**",
                ""
            ])

            for item in incident["evidence"]:
                lines.append(
                    f"- `{item['event_id']}` "
                    f"({item['type']}): {item['detail']}"
                )

            lines.extend([
                "",
                "**Assessment:**",
                "",
                incident["assessment"],
                ""
            ])

    lines.extend(["## Recommended Next Steps", ""])

    for recommendation in report["recommended_next_steps"]:
        lines.append(f"- {recommendation}")

    lines.extend(["", "## Limitations", ""])

    for limitation in report["limitations"]:
        lines.append(f"- {limitation}")

    lines.extend([
        "",
        "## Reproducibility",
        "",
        "This report was generated from the project's synthetic JSON "
        "evidence files using the Python detection and correlation pipeline.",
        "",
        "No live systems were accessed or modified.",
        ""
    ])

    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main():
    from src.loader import load_all_evidence

    ensure_output_directory()

    evidence = load_all_evidence()
    incidents = correlate_incident(evidence)
    report = build_report(evidence, incidents)

    json_path = save_json_report(report)
    markdown_path = save_markdown_report(report)

    print("\nREPORT GENERATION COMPLETE")
    print("=" * 45)
    print(f"Incidents identified: {report['incident_count']}")
    print(f"JSON report: {json_path.relative_to(PROJECT_ROOT)}")
    print(f"Markdown report: {markdown_path.relative_to(PROJECT_ROOT)}")
    print("\nOpen incident_report.md to review the findings.")


if __name__ == "__main__":
    main()
